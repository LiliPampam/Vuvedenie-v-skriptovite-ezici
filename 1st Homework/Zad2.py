# 2. Напишете програма, която взима число n от input и намира всички нечетни 
# делители на това число и ги принтира. Пример 6 -> 1, 3; 30 -> 1, 3, 5, 15

n = int(input("Enter a number: "))
a = []
for i in range (1, int(n/2)+1):
    if i % 2 != 0:
        if n % i == 0:
            a.append(i)
print(n, "->", a)